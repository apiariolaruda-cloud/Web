create extension if not exists pgcrypto;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  tracking_code text not null unique default (
    'LR-' || to_char(now(), 'YY') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6))
  ),
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  status text not null default 'pedido_ingresado' check (status in (
    'pedido_ingresado',
    'material_preparado',
    'reina_fecundada',
    'pendiente_pago',
    'pago_confirmado',
    'envio',
    'finalizado'
  )),
  estimated_date date,
  delivery_method text not null default 'A coordinar',
  total numeric(12,2) not null default 0 check (total >= 0),
  public_note text,
  internal_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_by uuid default auth.uid()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  description text not null,
  quantity numeric(10,2) not null default 1 check (quantity > 0),
  unit text not null default 'u.',
  unit_price numeric(12,2) check (unit_price is null or unit_price >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null check (status in (
    'pedido_ingresado',
    'material_preparado',
    'reina_fecundada',
    'pendiente_pago',
    'pago_confirmado',
    'envio',
    'finalizado'
  )),
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);

create index if not exists idx_orders_tracking_code on public.orders (tracking_code);
create index if not exists idx_orders_status on public.orders (status);
create index if not exists idx_orders_created_at on public.orders (created_at desc);
create index if not exists idx_order_items_order_id on public.order_items (order_id);
create index if not exists idx_order_status_history_order_id on public.order_status_history (order_id, created_at);

create or replace function public.set_order_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  new.updated_by = auth.uid();
  return new;
end;
$$;

drop trigger if exists trg_orders_updated_at on public.orders;
create trigger trg_orders_updated_at
before update on public.orders
for each row execute function public.set_order_updated_at();

create or replace function public.log_order_status_change()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_status_history (order_id, status, created_by)
    values (new.id, new.status, auth.uid());
  end if;
  return new;
end;
$$;

drop trigger if exists trg_order_status_history on public.orders;
create trigger trg_order_status_history
after insert or update of status on public.orders
for each row execute function public.log_order_status_change();

