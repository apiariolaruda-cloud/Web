-- =============================================================
-- FUNCIÓN PÚBLICA DE SEGUIMIENTO
-- Devuelve solamente los datos que el comprador puede ver.
-- No expone teléfono, email, notas internas ni datos de otros pedidos.
-- =============================================================

create or replace function public.get_public_order(p_tracking_code text)
returns jsonb
language sql
security definer
stable
set search_path = public
as $$
  select jsonb_build_object(
    'tracking_code', o.tracking_code,
    'status', o.status,
    'estimated_date', o.estimated_date,
    'delivery_method', o.delivery_method,
    'public_note', o.public_note,
    'created_at', o.created_at,
    'updated_at', o.updated_at,
    'items', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'description', i.description,
          'quantity', i.quantity,
          'unit', i.unit
        )
        order by i.sort_order, i.id
      )
      from public.order_items i
      where i.order_id = o.id
    ), '[]'::jsonb),
    'history', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'status', h.status,
          'created_at', h.created_at
        )
        order by h.created_at, h.id
      )
      from public.order_status_history h
      where h.order_id = o.id
    ), '[]'::jsonb)
  )
  from public.orders o
  where upper(trim(o.tracking_code)) = upper(trim(p_tracking_code))
  limit 1;
$$;

revoke all on function public.get_public_order(text) from public;
grant execute on function public.get_public_order(text) to anon, authenticated;



-- =============================================================
-- KEEPALIVE PARA PLAN FREE
--
-- Esta función está pensada para ser llamada por un servicio externo
-- (por ejemplo cron-job.org) varias veces al día. Hace una lectura mínima
-- de la tabla de pedidos y NO crea, modifica ni elimina información.
-- =============================================================

create or replace function public.la_ruda_keepalive()
returns jsonb
language sql
security definer
stable
set search_path = public
as $$
  select jsonb_build_object(
    'ok', (select count(*) from public.orders) >= 0,
    'checked_at', now()
  );
$$;

revoke all on function public.la_ruda_keepalive() from public;
grant execute on function public.la_ruda_keepalive() to anon, authenticated;

